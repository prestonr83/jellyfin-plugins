<#
.SYNOPSIS
    Runs the verification suite and generates an English Markdown summary.

.DESCRIPTION
    Converts the actual TRX results into docs/VERIFICATION-SUMMARY.md, including
    plugin and Jellyfin versions, environment details, and the outcome of each check.
    Checks requiring external services or explicit opt-in are reported as skipped.

.PARAMETER ConnectionString
    PostgreSQL administrator connection used to create and drop disposable test
    databases. Defaults to POSTGRES_TEST_CONNECTION. Use a dedicated test instance.

.PARAMETER OutputPath
    Summary destination. Defaults to docs/VERIFICATION-SUMMARY.md.

.PARAMETER Dotnet
    Path to the .NET SDK executable. Defaults to dotnet on PATH.

.PARAMETER NoRestore
    Uses packages already restored for the test project.

.EXAMPLE
    $env:POSTGRES_TEST_CONNECTION = 'Host=localhost;Port=5432;Database=postgres;Username=postgres;Password=...'
    ./Tools/Generate-VerificationSummary.ps1
#>
[CmdletBinding()]
param(
    [string]$ConnectionString = $env:POSTGRES_TEST_CONNECTION,
    [string]$OutputPath,
    [string]$Dotnet = 'dotnet',
    [switch]$NoRestore
)

$ErrorActionPreference = 'Stop'
$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$testProject = Join-Path $repoRoot 'Tests/Jellyfin.Database.Providers.Postgres.Tests/Jellyfin.Database.Providers.Postgres.Tests.csproj'
$resultsDir = Join-Path $repoRoot 'Tests/TestResults'
$trxName = 'verification.trx'
if (-not $OutputPath) { $OutputPath = Join-Path $repoRoot 'docs/VERIFICATION-SUMMARY.md' }

if ($ConnectionString) {
    $env:POSTGRES_TEST_CONNECTION = $ConnectionString
    Write-Host 'PostgreSQL configured: integration tests will also run.' -ForegroundColor Cyan
}
else {
    Write-Host 'POSTGRES_TEST_CONNECTION is unset: PostgreSQL integration tests will be skipped.' -ForegroundColor Yellow
}

Write-Host 'Running the verification suite...' -ForegroundColor Cyan
$trxPath = Join-Path $resultsDir $trxName
if (Test-Path -LiteralPath $trxPath) { Remove-Item -LiteralPath $trxPath }
$testArguments = @('test', $testProject, '--configuration', 'Release', '--logger', "trx;LogFileName=$trxName", '--results-directory', $resultsDir, '-m:1', '-nr:false', '-p:UseSharedCompilation=false')
if ($NoRestore) { $testArguments += '--no-restore' }
& $Dotnet @testArguments | Out-Host
$testExitCode = $LASTEXITCODE
if (-not (Test-Path -LiteralPath $trxPath)) {
    throw "No test results file was generated: $trxPath"
}

[xml]$trx = Get-Content -LiteralPath $trxPath
$ns = New-Object System.Xml.XmlNamespaceManager($trx.NameTable)
$ns.AddNamespace('t', 'http://microsoft.com/schemas/VisualStudio/TeamTest/2010')
$classes = @{}
foreach ($definition in $trx.SelectNodes('//t:UnitTest', $ns)) {
    $method = $definition.SelectSingleNode('t:TestMethod', $ns)
    if ($method) { $classes[$definition.id] = ($method.className -split '\.')[-1] }
}
$results = @(
    $trx.SelectNodes('//t:UnitTestResult', $ns) | ForEach-Object {
        $className = $classes[$_.testId]
        if (-not $className) { $className = (($_.testName -split '\(')[0] -split '\.')[-2] }
        [pscustomobject]@{ Name = $_.testName; Class = $className; Outcome = $_.outcome }
    }
)
$total = $results.Count
$failed = @($results | Where-Object { $_.Outcome -ne 'Passed' -and $_.Outcome -ne 'NotExecuted' })
$skipped = @($results | Where-Object { $_.Outcome -eq 'NotExecuted' })
$passed = @($results | Where-Object { $_.Outcome -eq 'Passed' }).Count
$areas = $results | Group-Object Class | Sort-Object Name | ForEach-Object {
    $bad = @($_.Group | Where-Object { $_.Outcome -ne 'Passed' -and $_.Outcome -ne 'NotExecuted' }).Count
    $skippedInArea = @($_.Group | Where-Object { $_.Outcome -eq 'NotExecuted' }).Count
    $state = if ($bad -gt 0) { "Failed: $bad" }
        elseif ($skippedInArea -eq $_.Count) { 'Skipped' }
        elseif ($skippedInArea -gt 0) { "Passed: $($_.Count - $skippedInArea)/$($_.Count) (remainder skipped)" }
        else { "Passed: $($_.Count)/$($_.Count)" }
    [pscustomobject]@{ Area = $_.Name; Checks = $_.Count; Result = $state }
}
[xml]$buildProperties = Get-Content -LiteralPath (Join-Path $repoRoot 'Directory.Build.props')
$pluginVersion = $buildProperties.SelectSingleNode('//Version').InnerText
$jellyfinVersion = $buildProperties.SelectSingleNode('//JellyfinVersion').InnerText
$databaseName = if ($ConnectionString) {
    (($ConnectionString -split ';' | Where-Object { $_ -match '^\s*Database\s*=' }) -replace '^\s*Database\s*=\s*', '').Trim()
}
else { 'not configured' }
$sdkVersion = (& $Dotnet --version).Trim()
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Verification summary')
$lines.Add('')
$lines.Add('> Generated by `Tools/Generate-VerificationSummary.ps1` from actual test results. Do not edit manually.')
$lines.Add('')
$lines.Add('| Detail | Value |')
$lines.Add('| --- | --- |')
$lines.Add("| Run date | $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss zzz') |")
$lines.Add("| Plugin version | $pluginVersion |")
$lines.Add("| Jellyfin build target | $jellyfinVersion |")
$lines.Add("| Test database | $databaseName |")
$lines.Add("| Environment | $([System.Runtime.InteropServices.RuntimeInformation]::OSDescription) / SDK $sdkVersion |")
$lines.Add('')
$lines.Add('## Overall result')
$lines.Add('')
$lines.Add('| Checks | Passed | Failed | Skipped |')
$lines.Add('| --- | --- | --- | --- |')
$lines.Add("| $total | $passed | $($failed.Count) | $($skipped.Count) |")
$lines.Add('')
$lines.Add('## Results by area')
$lines.Add('')
$lines.Add('| Area | Checks | Result |')
$lines.Add('| --- | --- | --- |')
foreach ($area in $areas) { $lines.Add("| $($area.Area) | $($area.Checks) | $($area.Result) |") }
$lines.Add('')
$lines.Add('## Details')
$lines.Add('')
$lines.Add('| Check | Result |')
$lines.Add('| --- | --- |')
foreach ($result in ($results | Sort-Object Name)) {
    $state = switch ($result.Outcome) {
        'Passed' { 'Passed' }
        'NotExecuted' { 'Skipped' }
        default { "Failed ($($result.Outcome))" }
    }
    $name = ($result.Name -replace '^Jellyfin\.Database\.Providers\.Postgres\.Tests\.', '') -replace '\|', '\|'
    $lines.Add("| $name | $state |")
}
if ($skipped.Count -gt 0) {
    $lines.Add('')
    $lines.Add('## Skipped checks')
    $lines.Add('')
    $lines.Add('These checks require external PostgreSQL, backup tools, or explicit environment settings. See the TRX results for individual skip reasons. Skipped checks are **not** counted as passed.')
    $lines.Add('')
    foreach ($result in $skipped) {
        $lines.Add("- $($result.Name -replace '^Jellyfin\.Database\.Providers\.Postgres\.Tests\.', '')")
    }
}
$lines.Add('')
$lines.Add('## Reproduce this report')
$lines.Add('')
$lines.Add('```powershell')
$lines.Add('# Run without PostgreSQL integration')
$lines.Add('dotnet test Tests/Jellyfin.Database.Providers.Postgres.Tests -c Release')
$lines.Add('')
$lines.Add('# Include integration against a dedicated PostgreSQL test instance')
$lines.Add('$env:POSTGRES_TEST_CONNECTION = "Host=localhost;Port=5432;Database=postgres;Username=postgres;Password=***"')
$lines.Add('./Tools/Generate-VerificationSummary.ps1')
$lines.Add('```')
$lines.Add('')
$lines.Add('Integration tests create disposable databases and drop them when finished. The supplied connection is used for CREATE DATABASE / DROP DATABASE.')
$outputDirectory = Split-Path -Parent ([System.IO.Path]::GetFullPath($OutputPath))
if (-not (Test-Path -LiteralPath $outputDirectory)) { New-Item -ItemType Directory -Force -Path $outputDirectory | Out-Null }
$lines -join [Environment]::NewLine | Set-Content -LiteralPath $OutputPath -Encoding UTF8
Write-Host "Summary generated: $OutputPath" -ForegroundColor Green
Write-Host "Result: $passed passed, $($failed.Count) failed, $($skipped.Count) skipped out of $total." -ForegroundColor Cyan
exit $testExitCode
